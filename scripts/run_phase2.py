"""Phase 2: segment catalogue, swap-set simulation, limits/bands, example proposal.

Uses the reference greedy builder (not the agent) to produce example swap sets.
Usage: python scripts/run_phase2.py   (needs phase 1 outputs)
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from csa import proposal, reference  # noqa: E402
from csa.lab import StrategyLab, plain  # noqa: E402
from run_phase1 import md_table  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "outputs" / "phase2"


def checks_table(sim):
    return md_table(pd.DataFrame(sim["limit_checks"])[["check", "value", "limit", "status"]], "{:,.3f}")


def main():
    t0 = time.time()
    OUT.mkdir(parents=True, exist_ok=True)
    lab = StrategyLab()
    cat = lab.build_catalogue()
    cat.drop(columns=["conds"]).to_csv(OUT / "catalogue_all_candidates.csv", index=False)
    ins, outs = lab.find_segments("swap_in", 50), lab.find_segments("swap_out", 50)
    (OUT / "segments_listed.json").write_text(json.dumps({"swap_in": ins, "swap_out": outs}, indent=1))
    funnel = (cat.groupby("kind").agg(candidates=("kind", "size"), found_on_build=("found_build", "sum"),
                                      confirmed_2015=("confirmed_oot", "sum"), listed_after_dedupe=("listed", "sum"))
              .reset_index())

    # Goal A: grow approvals >= 3% without raising the bad rate (delta <= 0)
    ga = reference.greedy(lab, 3.0, 0.0)
    sim_a = lab.simulate(ga["ins"], ga["outs"])
    prop = proposal.draft_test_proposal(lab, sim_a, "Grow approvals 3-5% without raising the bad rate")
    exp = proposal.export_strategy(lab, prop)
    (OUT / "example_simulation_goal_a.json").write_text(json.dumps(sim_a, indent=1))
    (OUT / "example_proposal_goal_a.json").write_text(json.dumps(prop, indent=1))
    (OUT / "example_proposal_goal_a.md").write_text(proposal.proposal_markdown(prop), encoding="utf-8")
    (OUT / "example_strategy_export_goal_a.json").write_text(json.dumps(exp, indent=1))

    # Breach goal: grow approvals 15% (appetite delta <= +0.2 pp)
    gb = reference.greedy(lab, 15.0, 0.2)
    sim_b = lab.simulate(gb["ins"], gb["outs"])
    within_delta = [h for h in gb["history"] if h["delta_bad_pp"] <= 0.2]
    max_growth_delta_only = max(within_delta, key=lambda h: h["growth_pct"])
    (OUT / "example_simulation_breach.json").write_text(json.dumps(sim_b, indent=1))

    hist = lambda g: md_table(pd.DataFrame([{"swap_ins": len(h["ins"]), "swap_outs": len(h["outs"]),
                                              "growth_pct": h["growth_pct"], "delta_bad_pp": h["delta_bad_pp"],
                                              "feasible": h["feasible"]} for h in g["history"]]), "{:,.3f}")
    base = lab.baseline("oot")
    r = ["# Phase 2 report (generated by scripts/run_phase2.py)", "",
         "Swap sets below come from the **reference greedy builder**, not the agent.", "",
         "## Baseline and marginal approved bad rate", "",
         md_table(pd.DataFrame([{k: v for k, v in base.items() if k != "policy"}])), "",
         f"Marginal approved bad rate (riskiest 10% of approvals): build **{100*lab.marginal['build']:.2f}%**, "
         f"2015 **{100*lab.marginal['oot']:.2f}%**.", "",
         "## Segment funnel", "", md_table(funnel), "",
         "## Swap-in candidates (listed)", "", md_table(pd.DataFrame(ins)), "",
         "## Swap-out candidates (listed, top 15)", "", md_table(pd.DataFrame(outs[:15])), "",
         "## Goal A: grow approvals >= 3% without raising the bad rate", "",
         f"Met by greedy: **{ga['met']}**. Swap-ins {ga['ins']}; swap-outs {ga['outs']}.", "",
         hist(ga), "",
         f"Final: growth **{sim_a['approval_growth_pct']}%**, Δ approval {sim_a['delta_approval_rate_pp']} pp, "
         f"Δ bad rate **{sim_a['delta_bad_rate_pp']} pp** (95% CI {sim_a['delta_bad_rate_ci95_pp']}), "
         f"band **{sim_a['band']}** → {sim_a['route']}.", "",
         f"New approvals by policy group: {sim_a['new_approvals_by_policy_group_pct']}", "",
         f"Volumes: {sim_a['volumes']}", "", checks_table(sim_a), ""]
    r += ["", "## Breach goal: grow approvals 15%", "",
          f"Met: **{gb['met']}**. Final state: growth {sim_b['approval_growth_pct']}%, Δ bad "
          f"{sim_b['delta_bad_rate_pp']} pp (CI {sim_b['delta_bad_rate_ci95_pp']}), band **{sim_b['band']}**.", "",
          f"Largest growth seen with Δ bad ≤ +0.2 pp (ignoring concentration): "
          f"**{max_growth_delta_only['growth_pct']}%** at Δ {max_growth_delta_only['delta_bad_pp']} pp.", "",
          hist(gb), "", f"Runtime: {round(time.time() - t0, 1)} s"]
    (OUT / "phase2_report.md").write_text("\n".join(r), encoding="utf-8")
    print(json.dumps({"funnel": funnel.to_dict("records"),
                      "goal_a": {k: sim_a[k] for k in ("approval_growth_pct", "delta_bad_rate_pp",
                                                       "delta_bad_rate_ci95_pp", "band",
                                                       "new_approvals_by_policy_group_pct")},
                      "breach": {k: sim_b[k] for k in ("approval_growth_pct", "delta_bad_rate_pp", "band")},
                      "max_growth_delta_only": max_growth_delta_only["growth_pct"],
                      "runtime_s": round(time.time() - t0, 1)}, indent=1, default=str))


if __name__ == "__main__":
    main()
