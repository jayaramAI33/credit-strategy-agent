"""Phase 1: data prep -> screening -> treatment -> binning/IV -> top features -> baseline.

Usage:
  python scripts/run_phase1.py            # reads the raw file (about 2-3 minutes)
  python scripts/run_phase1.py --cached   # reuses data/processed/loans.parquet
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from csa import binning, config, policy, prep, screening, treatment  # noqa: E402


def md_table(df: pd.DataFrame, floatfmt: str = "{:,.2f}") -> str:
    cols = list(df.columns)
    def cell(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else floatfmt.format(v)
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main(cached: bool) -> None:
    t0 = time.time()
    out = config.path("phase1_out"); out.mkdir(parents=True, exist_ok=True)
    pq = config.path("processed_file"); pq.parent.mkdir(parents=True, exist_ok=True)

    # A. population
    if cached and pq.exists():
        df = pd.read_parquet(pq)
        counts = json.loads((out / "counts.json").read_text())
    else:
        df, counts = prep.load_population()
        df.to_parquet(pq, index=False)
        (out / "counts.json").write_text(json.dumps(counts, indent=1))
    df = prep.add_derived(df)
    build, oot = df[df.split == "build"], df[df.split == "oot"]

    vint = (df.groupby("vintage").agg(loans=("bad", "size"), bad_pct=("bad", "mean"))
            .reset_index())
    vint["bad_pct"] *= 100
    vint["split"] = vint["vintage"].str[:4].astype(int).map(
        lambda y: "build" if y <= config.load("settings")["data"]["build_years"][1] else "oot")

    # C. screening
    log = screening.screen(build)
    log.to_csv(out / "screening_log.csv", index=False)
    feats = screening.kept_features(log)

    # D. treatment
    treated, ttable = treatment.fit_apply(df, feats)
    ttable.to_csv(out / "treatment_table.csv", index=False)

    # E/G. binning, IV, stability
    yb, yo = build["bad"], oot["bad"]
    bmask = df.split == "build"
    specs, tables, ivrows, woe_b = {}, [], [], {}
    for var, kind in zip(feats.variable, feats.kind):
        xb, xo = treated.loc[bmask, var], treated.loc[~bmask, var]
        spec = binning.fit(var, kind, xb, yb)
        t, m = binning.evaluate(spec, xb, yb, xo, yo)
        specs[var] = spec; tables.append(t); ivrows.append(m)
        woe_b[var] = binning.woe_encode(spec, xb, t)
    iv = pd.DataFrame(ivrows).sort_values("iv_build", ascending=False)
    iv["source"] = iv.variable.map(dict(zip(log.variable, log.source)))
    iv["policy_variable"] = iv.variable.isin(config.load("fields")["policy_variables"])
    bins = pd.concat(tables, ignore_index=True)
    iv.to_csv(out / "iv_table.csv", index=False)
    bins.to_csv(out / "bins_all.csv", index=False)
    sel = binning.select_top(iv, pd.DataFrame(woe_b))
    sel.to_csv(out / "selection.csv", index=False)
    top = sel[sel.selected].variable.tolist()
    spec_json = {v: {"kind": s.kind, "edges": s.edges, "groups": dict(s.groups),
                     "direction": s.direction} for v, s in specs.items()}
    (out / "binning_spec.json").write_text(json.dumps(spec_json, indent=1))

    # Current policy baseline (raw values)
    appr = policy.approve(df)
    base_split = policy.baseline(df, appr, "split")
    base_vint = policy.baseline(df, appr, "vintage")
    base_split.to_csv(out / "baseline_by_split.csv", index=False)
    base_vint.to_csv(out / "baseline_by_vintage.csv", index=False)

    metrics = {
        "counts": counts,
        "rows": int(len(df)),
        "bad_pct": {"build": 100 * float(yb.mean()), "oot": 100 * float(yo.mean())},
        "screening": log.status.value_counts().to_dict(),
        "top_features": top,
        "baseline": base_split.set_index("split").to_dict("index"),
        "runtime_sec": round(time.time() - t0, 1),
    }
    (out / "phase1_metrics.json").write_text(json.dumps(metrics, indent=1, default=float))

    # Report
    r = ["# Phase 1 report (generated by scripts/run_phase1.py)", ""]
    r += ["## A. Population", "", md_table(pd.DataFrame([counts])), "",
          f"Kept loans: **{len(df):,}**. Bad rate build **{metrics['bad_pct']['build']:.2f}%**, "
          f"OOT **{metrics['bad_pct']['oot']:.2f}%**.", "", "### Bad rate by vintage", "",
          md_table(vint), ""]
    r += ["## C. Screening (build years)", "",
          md_table(log.status.value_counts().rename_axis("status").reset_index()), "",
          md_table(log[["variable", "kind", "source", "missing_pct", "levels", "top_share_pct",
                        "status", "reason", "note"]]), ""]
    r += ["## D. Treatment", "", md_table(ttable), ""]
    r += ["## E. IV table (build bins; OOT on the same bins)", "",
          md_table(iv[["variable", "source", "policy_variable", "n_bins", "direction",
                       "iv_build", "iv_oot", "psi", "monotonic_oot"]], "{:,.3f}"), ""]
    r += ["## G. Top features for segments", "", md_table(sel, "{:,.3f}"), ""]
    for v in top:
        r += [f"### {v}", "", md_table(bins[bins.variable == v][
            ["bin", "vol_build_pct", "bad_build_pct", "vol_oot_pct", "bad_oot_pct", "woe"]]), ""]
    r += ["## Current policy baseline", "", md_table(base_split), "", md_table(base_vint), ""]
    r += [f"Runtime: {metrics['runtime_sec']} s"]
    (out / "phase1_report.md").write_text("\n".join(r), encoding="utf-8")
    print(json.dumps({k: metrics[k] for k in ("rows", "bad_pct", "screening", "top_features",
                                               "runtime_sec")}, indent=1, default=float))
    print(base_split.round(2).to_string(index=False))


if __name__ == "__main__":
    main(cached="--cached" in sys.argv)
